"""Generate tbl/jp.tbl (16-bit glyph code -> character) for /font/pfont12z.imb and the half-width font.

Order (checked against the font by eye, work/re/font_*.png): JIS X 0208 rows 1-8 (defined cells), NEC row 13
(cells 1-18 and 21-23 hold game icons -> {iXXX}), school kanji grades 1-3, extras. Half-width 0x4000|h: ASCII h-0x10,
JIS X 0201 katakana at h = 0xB1..0xEF (code - 0x10 = 0xA1..0xDF).
    python -X utf8 tools/mktbl.py
"""
