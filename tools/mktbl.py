G3 = ("悪安暗医委意育員院飲運泳駅央横屋温化荷界開階寒感漢館岸起期客究急級宮球去橋業曲局銀区苦具君係軽血決研県庫湖向幸港号根祭皿"
      "仕死使始指歯詩次事持式実写者主守取酒受州拾終習集住重宿所暑助昭消商章勝乗植申身神真深進世整昔全相送想息速族他打対待代第題"
      "炭短談着注柱丁帳調追定庭笛鉄転都度投豆島湯登等動童農波配倍箱畑発反坂板皮悲美鼻筆氷表秒病品負部服福物平返勉放味命面問役薬"
      "由油有遊予羊洋葉陽様落流旅両緑礼列練路和")
EXTRA = "宝堂斗郎妖洞院"
assert (len(G1), len(G2), len(G3)) == (80, 160, 200)


def table():
    t = []
    for row in range(1, 9):
        for col in range(1, 95):
            try:
                t.append(bytes([row + 0xA0, col + 0xA0]).decode("euc_jp"))
            except UnicodeDecodeError:
                pass
    assert len(t) == 0x20C
    for col in range(1, 95):
        s2 = col + 0x3F + (1 if col >= 64 else 0)
        try:
            t.append(bytes([0x87, s2]).decode("cp932"))
        except UnicodeDecodeError:
            pass
    assert len(t) == 0x25F, hex(len(t))
    for c in list(range(0x20C, 0x21E)) + list(range(0x220, 0x224)):
        t[c] = "{i%03X}" % c
    t += list(G1 + G2 + G3 + EXTRA)
    m = {c: ch for c, ch in enumerate(t)}
    for h in range(0x20, 0x7F):
        m[0x4000 | (h + 0x10)] = "{h%s}" % chr(h) if h != 0x20 else "{h }"
    for h in range(0xA1, 0xE0):
        m[0x4000 | (h + 0x10)] = "{h%s}" % bytes([h]).decode("cp932")
    return m


if __name__ == "__main__":
    m = table()
    seen = set()
    with open(os.path.join(ROOT, "tbl", "jp.tbl"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# generated by tools/mktbl.py; duplicate chars: the first code wins on encode\n")
        for c in sorted(m):
            f.write("%04X=%s\n" % (c, m[c]))
    print(len(m), "codes")
