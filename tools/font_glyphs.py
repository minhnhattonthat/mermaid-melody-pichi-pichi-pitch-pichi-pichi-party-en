# English proportional font for the 12x12 text engine. Rows 0-11, baseline = row 9 (last row of capitals).
# '#' = colour 3 (body), '+' = colour 2 (edge), '.' = transparent. Glyph width = art width; advance = width + 1.
G = {}

def g(ch, art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == 12, (ch, len(rows))
    w = len(rows[0])
    assert all(len(r) == w for r in rows), ch
    G[ch] = rows

