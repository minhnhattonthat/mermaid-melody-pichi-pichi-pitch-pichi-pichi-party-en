def render_tiny(text, spacing=1, space=2):
    cols = []
    for i, ch in enumerate(text):
        if ch == " ":
            cols.append(np.zeros((5, space), np.uint8)); continue
        rows = _T[ch]
        w = max(len(r) for r in rows)
        g = np.array([[c == "#" for c in r.ljust(w, ".")] for r in rows], np.uint8)
        cols.append(g)
        if i + 1 < len(text) and text[i + 1] != " ":
            cols.append(np.zeros((5, spacing), np.uint8))
    return np.concatenate(cols, axis=1)


def _glyph(ch, bold=False):
    rows = _GB[ch] if bold and ch in _GB else _G[ch]
    w = max(len(r) for r in rows)
    a = np.zeros((9, w), np.uint8)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            a[y, x] = c == "#"
    return a


def render(text, bold=False, scale=1, spacing=1, space=3):
    cols = []
    if bold and space == 3:
        space = 4
    for i, ch in enumerate(text):
        if ch == " ":
            cols.append(np.zeros((9, space), np.uint8))
            continue
        g = _glyph(ch, bold)
        if bold:
            g = np.pad(g, ((0, 0), (0, 1)))
            g[:, 1:] |= g[:, :-1]
        cols.append(g)
        if i + 1 < len(text) and text[i + 1] != " ":
            cols.append(np.zeros((9, spacing), np.uint8))
    m = np.concatenate(cols, axis=1) if cols else np.zeros((9, 0), np.uint8)
    if scale > 1:
        m = m.repeat(scale, 0).repeat(scale, 1)
    return m


def trim_rows(m):
    """Cut empty descender rows when the text has none."""
    rows = np.nonzero(m.any(1))[0]
    return m[: rows.max() + 1] if len(rows) else m


def dilate(m, r=1, diag=True):
    o = np.pad(m, r)
    out = np.zeros_like(o)
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            if not diag and dy and dx:
                continue
            out |= np.roll(np.roll(o, dy, 0), dx, 1)
    return out


def compose(dst, x, y, mask, ink, outline=None, shadow=None, diag=True):
    """Draw mask at (x, y) into index array dst. outline = index of a 1-px ring, shadow = (index, dx, dy)."""
    h, w = mask.shape
    if shadow is not None:
        si, dx, dy = shadow
        src = dilate(mask, 1, diag) if outline is not None else np.pad(mask, 1)
        _put(dst, x - 1 + dx, y - 1 + dy, src, si)
    if outline is not None:
        _put(dst, x - 1, y - 1, dilate(mask, 1, diag), outline)
    _put(dst, x, y, mask, ink)


def _put(dst, x, y, m, v):
    H, W = dst.shape
    for yy, xx in zip(*np.nonzero(m)):
        X, Y = x + xx, y + yy
        if 0 <= X < W and 0 <= Y < H:
            dst[Y, X] = v


def width(text, **kw):
    return render(text, **kw).shape[1]


